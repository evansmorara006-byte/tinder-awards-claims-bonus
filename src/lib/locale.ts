export const readAcceptLanguage = createServerFn({ method: "GET" }).handler(async () => {
  const { getRequest } = await import("@tanstack/react-start/server");
  try {
    return getRequest()?.headers.get("accept-language") ?? "";
  } catch {
    return "";
  }
});

export function localeFromHeader(header: string | null | undefined) {
  const first = String(header ?? "")
    .split(",")[0]
    ?.split(";")[0]
    ?.trim();
  return first || "en";
}

