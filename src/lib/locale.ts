function langOf(locale: string) {
  const value = locale.toLowerCase();
  if (value.startsWith("zh")) return "zh";
  const base = value.split("-")[0];
  return base in packs ? base : "en";
}

export function systemLocale() {
  if (typeof navigator === "undefined") return "en";
  const list = [...(navigator.languages ?? []), navigator.language].filter(Boolean);
  if (list[0]) return list[0];
  try {
    return Intl.DateTimeFormat().resolvedOptions().locale || "en";
  } catch {
    return "en";
  }
}

function applyDocumentLocale(locale: string) {
  if (typeof document === "undefined") return;
  document.documentElement.lang = locale;
  document.documentElement.dir = /^(ar|he|fa|ur)\b/i.test(locale) ? "rtl" : "ltr";
}

/** Prefer the device language. A webview that only reports English still follows the request language. */
export function chooseLocale(header = "") {
  const stored =
    header ||
    (typeof window !== "undefined" ? String((window as Window & { __ACCEPT_LANGUAGE?: string }).__ACCEPT_LANGUAGE ?? "") : "");
  const fromHeader = localeFromHeader(stored);
  const fromSystem = typeof navigator === "undefined" ? "" : systemLocale();
  if (fromSystem && langOf(fromSystem) !== "en") return fromSystem;
  if (fromHeader && langOf(fromHeader) !== "en") return fromHeader;
  return fromSystem || fromHeader || "en";
}

export function translate(locale: string, key: Key, vars?: Record<string, string>) {
  const table = packs[langOf(locale)] ?? en;
  let text = table[key] || en[key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, value);
  }
  return text;
}

const labelCache = new Map<string, Map<string, string>>();

export function countryLabel(name: string, locale: string) {
  let labels = labelCache.get(locale);
  if (!labels) {
    labels = new Map();
    labelCache.set(locale, labels);
  }
  const cached = labels.get(name);
  if (cached) return cached;
  const iso = countryIso(name);
  let label = name;
  if (iso) {
    try {
      label = new Intl.DisplayNames([locale], { type: "region" }).of(iso) || name;
    } catch {
      label = name;
    }
  }
  labels.set(name, label);
  return label;
}

