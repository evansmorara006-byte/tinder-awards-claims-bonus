export function localizeMessage(message: string, locale: string, country = "") {
  const key = NOTICE_KEYS[message];
  if (key) return translate(locale, key);
  if (message.startsWith("Enter a real ")) {
    return translate(locale, "phoneInvalid", { country: country ? countryLabel(country, locale) : country });
  }
  if (/failed to fetch|network|abort/i.test(message)) return translate(locale, "submitRetry");
  return message;
}

export function useLocale() {
  const hint = useContext(LocaleHint);
  const [locale, setLocale] = useState(() => chooseLocale(hint));
  useLayoutEffect(() => {
    const apply = () => {
      const next = chooseLocale(hint);
      setLocale(next);
      applyDocumentLocale(next);
    };
    apply();
    window.addEventListener("languagechange", apply);
    return () => window.removeEventListener("languagechange", apply);
  }, [hint]);
  const t = (key: Key, vars?: Record<string, string>) => translate(locale, key, vars);
  return { locale, t };
}
